document.addEventListener('DOMContentLoaded', () => {
    initTheme();
    document.getElementById('theme-toggle')?.addEventListener('click', toggleTheme);

    // Configure marked.js to sanitize output
    if (typeof marked !== 'undefined') {
        marked.setOptions({ breaks: true });
    }
});

function initTheme() {
    const saved = localStorage.getItem('theme');
    const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
    applyTheme(saved || (prefersDark ? 'dark' : 'light'));
}

function toggleTheme() {
    const current = document.documentElement.getAttribute('data-theme');
    const next = current === 'dark' ? 'light' : 'dark';
    applyTheme(next);
    localStorage.setItem('theme', next);
}

function applyTheme(theme) {
    document.documentElement.setAttribute('data-theme', theme);
}

// =============================================================================
// Code Tabs
// =============================================================================

function switchTab(tabId) {
    document.querySelectorAll('.code-block').forEach(el => el.classList.add('hidden'));
    document.querySelectorAll('.code-tab').forEach(el => el.classList.remove('active'));

    const panel = document.getElementById('tab-' + tabId);
    if (panel) panel.classList.remove('hidden');

    const btn = [...document.querySelectorAll('.code-tab')].find(b =>
        b.onclick?.toString().includes(tabId)
    );
    if (btn) btn.classList.add('active');
}

