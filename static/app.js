let demoRunning = false;

const SIMULATED_REPORT = `## Research Report

### Executive Summary

This multi-agent research workflow demonstrates how three specialized AI agents collaborate to produce comprehensive research. Each agent contributes its unique strengths through the A2A (Agent-to-Agent) protocol.

### Key Findings

**1. Agent Specialization Matters**
By assigning specific roles — web search, deep analysis, and cross-validation — each agent operates in its area of strength, producing higher quality results than any single model alone.

**2. A2A Protocol Enables Interoperability**
The standardized JSON-RPC communication layer allows seamless coordination between agents from different providers (Anthropic, OpenAI, Perplexity) without vendor lock-in.

**3. Real-Time Streaming Improves UX**
Server-Sent Events provide live progress updates during the multi-step workflow, keeping users informed as agents collaborate behind the scenes.

### Sources
1. A2A Protocol Specification — Google Research (2024)
2. Multi-Agent Systems in Practice — arXiv:2401.xxxxx
3. FastAPI Documentation — tiangolo.github.io/fastapi

### Methodology
- **Discovery Phase**: Perplexity searched 12 web sources
- **Analysis Phase**: Claude synthesized findings with structured reasoning
- **Validation Phase**: OpenAI cross-referenced claims across sources

---
*Generated by ResearchAgent — Powered by A2A Protocol*`;

async function runDemo() {
    if (demoRunning) return;

    const query = document.getElementById('query-input')?.value.trim();
    if (!query) {
        showToast('Enter a research query to try the demo', 'error');
        document.getElementById('query-input')?.focus();
        return;
    }

    demoRunning = true;
    const btn = document.getElementById('search-btn');
    if (btn) btn.disabled = true;

    // Show sections
    show('demo-progress');
    show('demo-log');
    hide('demo-results');

    // Clear log
    clearLog();

    // Reset agents
    resetAgents();

    // Simulated workflow timeline (delays are relative to previous step)
    const steps = [
        { wait: 300,  fn: () => { updateProgress(5, 'Initializing orchestrator...'); logMsg('Orchestrator', 'Planning research for: "' + truncate(query, 60) + '"', 'orchestrator'); }},
        { wait: 700,  fn: () => { updateProgress(10, 'Creating research plan...'); logMsg('Orchestrator', 'Identified 3 sub-topics. Dispatching to agents via A2A...', 'orchestrator'); }},
        { wait: 800,  fn: () => { setAgent('perplexity', 'working'); updateProgress(20, 'Perplexity: Searching the web...'); logMsg('Perplexity', 'Initiating web search across multiple sources...', 'perplexity'); }},
        { wait: 1200, fn: () => { updateProgress(30, 'Perplexity: Gathering citations...'); logMsg('Perplexity', 'Found 12 relevant sources with citations. Packaging results...', 'perplexity'); }},
        { wait: 1000, fn: () => { setAgent('perplexity', 'done'); setAgent('claude', 'working'); updateProgress(40, 'Claude: Analyzing findings...'); logMsg('Claude', 'Received search results. Beginning deep analysis...', 'claude'); }},
        { wait: 1500, fn: () => { updateProgress(55, 'Claude: Synthesizing report...'); logMsg('Claude', 'Cross-referencing claims. Structuring findings into report...', 'claude'); }},
        { wait: 1500, fn: () => { setAgent('claude', 'done'); setAgent('openai', 'working'); updateProgress(70, 'OpenAI: Validating claims...'); logMsg('OpenAI', 'Running cross-validation against source material...', 'openai'); }},
        { wait: 1500, fn: () => { updateProgress(85, 'OpenAI: Checking consistency...'); logMsg('OpenAI', 'Verified 95% claim accuracy. 2 minor corrections applied.', 'openai'); }},
        { wait: 1000, fn: () => { setAgent('openai', 'done'); updateProgress(95, 'Assembling final report...'); logMsg('Orchestrator', 'All agents complete. Assembling final synthesis...', 'orchestrator'); }},
        { wait: 1000, fn: () => { updateProgress(100, 'Research complete!'); showResults(); }},
    ];

    for (const step of steps) {
        await delay(step.wait);
        step.fn();
    }

    if (btn) btn.disabled = false;
    demoRunning = false;
}

function showResults() {
    show('demo-results');
    const content = document.getElementById('results-content');
    if (content && typeof marked !== 'undefined') {
        content.innerHTML = marked.parse(SIMULATED_REPORT);
    } else if (content) {
        content.textContent = SIMULATED_REPORT;
    }
    document.getElementById('demo-results')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
    showToast('Simulated research complete!');
}

