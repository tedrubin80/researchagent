function updateProgress(pct, text) {
    const bar = document.getElementById('progress-bar');
    const pctEl = document.getElementById('progress-percent');
    const textEl = document.getElementById('progress-text');
    if (bar) bar.style.width = pct + '%';
    if (pctEl) pctEl.textContent = pct + '%';
    if (textEl) textEl.textContent = text;
}

function setAgent(id, state) {
    const el = document.getElementById('agent-' + id);
    if (!el) return;
    el.classList.remove('working', 'done', 'active');
    if (state) el.classList.add(state);
}

function resetAgents() {
    ['perplexity', 'claude', 'openai'].forEach(id => setAgent(id, null));
    updateProgress(0, 'Initializing...');
}

function clearLog() {
    const log = document.getElementById('log-container');
    if (log) {
        while (log.firstChild) log.removeChild(log.firstChild);
    }
}

function logMsg(sender, message, cls) {
    const log = document.getElementById('log-container');
    if (!log) return;

    const ts = new Date().toLocaleTimeString('en-US', {
        hour12: false, hour: '2-digit', minute: '2-digit', second: '2-digit'
    });

    const entry = document.createElement('div');
    entry.className = 'log-entry';

    const tsSpan = document.createElement('span');
    tsSpan.className = 'log-timestamp';
    tsSpan.textContent = '[' + ts + ']';

    const senderSpan = document.createElement('span');
    senderSpan.className = 'log-sender ' + cls;
    senderSpan.textContent = sender + ':';

    const msgSpan = document.createElement('span');
    msgSpan.className = 'log-message';
    msgSpan.textContent = message;

    entry.appendChild(tsSpan);
    entry.appendChild(senderSpan);
    entry.appendChild(msgSpan);

    log.appendChild(entry);
    log.scrollTop = log.scrollHeight;
}

function show(id) { document.getElementById(id)?.classList.add('visible'); }
function hide(id) { document.getElementById(id)?.classList.remove('visible'); }
function delay(ms) { return new Promise(r => setTimeout(r, ms)); }
function truncate(s, n) { return s.length > n ? s.slice(0, n) + '...' : s; }

function showToast(message) {
    const toast = document.getElementById('toast');
    const msg = document.getElementById('toast-message');
    if (!toast || !msg) return;
    msg.textContent = message;
    toast.classList.add('visible');
    setTimeout(() => toast.classList.remove('visible'), 3000);
}

